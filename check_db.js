const Database = require('./node_modules/better-sqlite3');
const db = new Database('./pil_claims.db');
const tables = db.prepare("SELECT name FROM sqlite_master WHERE type='table'").all();
console.log('TABLES:', JSON.stringify(tables.map(t => t.name)));
const users = db.prepare('SELECT COUNT(*) as c FROM users').get();
const claims = db.prepare('SELECT COUNT(*) as c FROM claims').get();
const surveys = db.prepare('SELECT COUNT(*) as c FROM surveys').get();
const audits = db.prepare('SELECT COUNT(*) as c FROM audit_logs').get();
const exps = db.prepare('SELECT COUNT(*) as c FROM expenses').get();
const recs = db.prepare('SELECT COUNT(*) as c FROM recoveries').get();
const notifs = db.prepare('SELECT COUNT(*) as c FROM notifications').get();
const rates = db.prepare('SELECT COUNT(*) as c FROM currency_rates').get();
const lms = db.prepare('SELECT COUNT(*) as c FROM lms_cache').get();
console.log('RECORD COUNTS:', JSON.stringify({users:users.c, claims:claims.c, surveys:surveys.c, audit_logs:audits.c, expenses:exps.c, recoveries:recs.c, notifications:notifs.c, currency_rates:rates.c, lms_cache:lms.c}));
const sampleClaim = db.prepare('SELECT id, claim_number, status, bl_number, created_date FROM claims LIMIT 3').all();
console.log('SAMPLE CLAIMS:', JSON.stringify(sampleClaim));
const sampleUsers = db.prepare('SELECT id, email, role, is_verified FROM users').all();
console.log('USERS:', JSON.stringify(sampleUsers));
db.close();
